/* Bounded packet bridge between the single core1 drive task and the existing
 * kernel CYW43/MQTT owner. Public declarations are libc-friendly and contain
 * no T-Kernel types; drive_bridge.c owns the kernel MBFs and mutex. */
#ifndef DRIVE_B1_BRIDGE_H
#define DRIVE_B1_BRIDGE_H

#include <stdbool.h>
#include <stdint.h>
#include "../subsystem2/controller/wifi_transport_status.h"

#define DRIVE_BRIDGE_PACKET_MAX 64u
#define DRIVE_BRIDGE_RX_COPY_MAX 8u

/* Call once during phase-1 kernel initialization, before starting the drive
 * task or allowing mqtt_utk_start() to poll. Returns E_OK or a kernel error. */
int32_t drive_bridge_init(void);
bool drive_bridge_ready(void);

/* TX is generated by the core1 controller and drained by the core0 MQTT
 * service. Payload bytes are copied; calls never wait for a queue slot. */
bool drive_bridge_tx_enqueue(uint8_t topic,const uint8_t *data,uint32_t length);
bool drive_bridge_tx_take(uint8_t *topic,uint8_t data[DRIVE_BRIDGE_PACKET_MAX],uint32_t *length);

/* RX is copied by the core0 MQTT service, then consumed by the core1
 * controller. original_length is retained even when only eight bytes fit. */
bool drive_bridge_rx_enqueue(const uint8_t copied[DRIVE_BRIDGE_RX_COPY_MAX],
                             uint8_t copied_length,uint32_t original_length);
bool drive_bridge_rx_take(uint8_t data[DRIVE_BRIDGE_RX_COPY_MAX],uint32_t *original_length);

/* Network owner publishes a coherent status snapshot under a bounded
 * TMO_POL mutex. If the mutex is busy, caller skips this update/read. */
bool drive_bridge_status_update(const WifiTransportStatus *status);
bool drive_bridge_status_snapshot(WifiTransportStatus *status);
void drive_bridge_publish_result(bool published);

#endif
